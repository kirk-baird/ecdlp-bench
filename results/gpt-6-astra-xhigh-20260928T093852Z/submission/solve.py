"""An honest generic ECDLP baseline, NOT a polylogarithmic algorithm.

Small groups use baby-step giant-step with the negation symmetry. Larger
groups use a constant-storage Pollard rho walk. Both require on the order
of sqrt(n) group operations, and cannot solve the full benchmark in time.
Only the Python standard library is used.
"""

from math import isqrt
from random import Random


_MAX_BABIES = 1 << 20


def _add(P, Q, a, p):
    if P is None:
        return Q
    if Q is None:
        return P
    x, y = P
    u, v = Q
    if x == u:
        if (y + v) % p == 0:
            return None
        slope = (3 * x * x + a) * pow(2 * y, -1, p) % p
    else:
        slope = (v - y) * pow(u - x, -1, p) % p
    rx = (slope * slope - x - u) % p
    return rx, (slope * (x - rx) - y) % p


def _neg(P, p):
    return None if P is None else (P[0], -P[1] % p)


def _mul(k, P, a, p):
    R = None
    while k:
        if k & 1:
            R = _add(R, P, a, p)
        k >>= 1
        if k:
            P = _add(P, P, a, p)
    return R


def _bsgs(p, a, n, G, Q, m):
    """Search centered intervals of width 2*m+1 using x-coordinate keys."""
    babies = {}
    P = G
    for j in range(1, m + 1):
        if P is not None:
            # The stored scalar represents the point with even y. For odd
            # p, P and -P have opposite y parity unless P has order two.
            babies[P[0]] = -j if P[1] & 1 else j
        P = _add(P, G, a, p)

    width = 2 * m + 1
    step = _neg(_mul(width, G, a, p), p)
    R = Q
    for i in range((n - 1 + m) // width + 1):
        if R is None:
            candidate = i * width % n
        else:
            j = babies.get(R[0])
            if j is None:
                R = _add(R, step, a, p)
                continue
            if R[1] & 1:
                j = -j
            candidate = (i * width + j) % n
        if _mul(candidate, G, a, p) == Q:
            return candidate
        raise ValueError("inconsistent group order or point arithmetic")
    raise ValueError("Q is not in the subgroup generated by G")


def _rho(p, a, n, G, Q):
    """A 32-part adding walk with Brent cycle detection and fresh restarts.

    The sqrt(n) expectation relies on the usual random-walk heuristic.
    No claim of a polynomial running time is made.
    """
    rng = Random((p << 1) ^ (n << 3) ^ (G[0] << 5) ^ Q[0] ^ (Q[1] << 7))
    parts = 32
    walk_limit = 8 * (isqrt(n) + 1)
    while True:
        jumps = []
        while len(jumps) < parts:
            u, v = rng.randrange(n), rng.randrange(n)
            P = _add(_mul(u, G, a, p), _mul(v, Q, a, p), a, p)
            if P is not None:
                jumps.append((P, u, v))

        u, v = rng.randrange(n), rng.randrange(n)
        P = _add(_mul(u, G, a, p), _mul(v, Q, a, p), a, p)
        saved_P, saved_u, saved_v = P, u, v
        power, distance = 1, 0
        for _ in range(walk_limit):
            index = 0 if P is None else P[0] & (parts - 1)
            jump, du, dv = jumps[index]
            P = _add(P, jump, a, p)
            u, v = (u + du) % n, (v + dv) % n
            distance += 1
            if P == saved_P:
                denominator = (v - saved_v) % n
                if denominator:
                    k = (saved_u - u) * pow(denominator, -1, n) % n
                    if _mul(k, G, a, p) == Q:
                        return k
                break
            if distance == power:
                saved_P, saved_u, saved_v = P, u, v
                power *= 2
                distance = 0


def solve(p, a, b, n, G, Q) -> int:
    """Return k in [0,n) with k*G == Q, using exponential generic search.

    Preconditions: p is an odd prime; the curve is nonsingular; G has
    prime order n; Q belongs to <G>. Infinity (None) is also supported.
    Cryptographic-size random inputs will not finish in practical time.
    """
    if p <= 2 or n < 2:
        raise ValueError("expected an odd prime field and prime order n >= 2")
    a, b = a % p, b % p
    if (4 * a * a * a + 27 * b * b) % p == 0:
        raise ValueError("singular curve")
    if G is None:
        raise ValueError("G must have order n >= 2")
    G = (int(G[0]) % p, int(G[1]) % p)
    if Q is not None:
        Q = (int(Q[0]) % p, int(Q[1]) % p)
    for P in (G, Q):
        if P is not None:
            x, y = P
            if (y * y - x * x * x - a * x - b) % p:
                raise ValueError("point is not on the curve")
    if Q is None:
        return 0
    if Q == G:
        return 1
    if Q == _neg(G, p):
        return n - 1
    m = isqrt(n // 2) + 1
    if m <= _MAX_BABIES:
        return _bsgs(p, a, n, G, Q, m)
    return _rho(p, a, n, G, Q)
